"""Slack Bolt Bot for Mediator using Socket Mode.

Provides:
- Mention-triggered alignment analysis (@Mediator in channels)
- Safe conversation context extraction
- Event deduplication and loop prevention
- Structured thread responses with conflict evidence and dashboard links
- Governance adherence: Never modifies commitments or decisions without user confirmation
"""

import asyncio
import logging
import time
from typing import Any, Dict, Optional, Set

from slack_bolt import App
from slack_bolt.adapter.socket_mode import SocketModeHandler

from app.config import settings
from app.services.analysis import analysis_service
from app.slack.service import slack_service

logger = logging.getLogger(__name__)

# Deduplication cache for incoming event IDs with TTL (in seconds)
_PROCESSED_EVENTS: Dict[str, float] = {}
_EVENT_TTL = 300.0  # 5 minutes


def _is_duplicate_event(event_id: str) -> bool:
    """Checks whether an event was already processed within the TTL window."""
    now = time.time()
    # Prune expired entries
    expired = [k for k, v in _PROCESSED_EVENTS.items() if now - v > _EVENT_TTL]
    for k in expired:
        _PROCESSED_EVENTS.pop(k, None)

    if event_id in _PROCESSED_EVENTS:
        return True
    _PROCESSED_EVENTS[event_id] = now
    return False


def create_slack_app() -> Optional[App]:
    """Initializes and returns the Slack Bolt App with event listeners."""
    if not settings.slack_bot_token:
        logger.warning("SLACK_BOT_TOKEN not configured. Slack Bot will not start.")
        return None

    app = App(
        token=settings.slack_bot_token,
        signing_secret=settings.slack_signing_secret,
        token_verification_enabled=False,
    )

    # -------------------------------------------------------------
    # Event: app_mention (@Mediator ...)
    # -------------------------------------------------------------
    @app.event("app_mention")
    def handle_app_mention(event: Dict[str, Any], client: Any, say: Any):
        """Triggered whenever @Mediator is tagged in a project channel."""
        event_id = event.get("client_msg_id") or f"{event.get('channel')}_{event.get('ts')}"
        if _is_duplicate_event(event_id):
            logger.info(f"Skipping duplicate Slack event: {event_id}")
            return

        # Loop prevention: Ignore any message originating from bots
        if event.get("bot_id"):
            logger.info("Ignoring event generated by a bot user to prevent loops.")
            return

        channel_id = event.get("channel")
        trigger_ts = event.get("ts")
        thread_ts = event.get("thread_ts", trigger_ts)
        user_id = event.get("user")
        raw_text = event.get("text", "")

        logger.info(f"Received @Mediator mention from user {user_id} in channel {channel_id}")

        # Check for simple help or status queries
        cleaned_command = slack_service.clean_slack_text(raw_text).lower().strip()
        if cleaned_command in ["help", "--help", "-h"]:
            client.chat_postMessage(
                channel=channel_id,
                thread_ts=thread_ts,
                text=(
                    "👋 *Mediator AI Alignment Teammate*\n\n"
                    "I help groups detect hidden disagreements, clarify responsibilities, and reach consensus.\n\n"
                    "• *How to use*: Just mention `@Mediator` in any channel or thread after discussing project plans.\n"
                    "• *What I do*: I analyze recent team messages, compare assumptions, detect conflicting deadlines or ownership gaps, and propose resolutions.\n"
                    "• *Dashboard*: Review detailed evidence and approve commitments in your browser.\n"
                    "• *Governance*: I *never* alter responsibilities or finalize decisions automatically without human team approval."
                ),
            )
            return

        # Immediate acknowledgement in thread
        ack_msg = client.chat_postMessage(
            channel=channel_id,
            thread_ts=thread_ts,
            text="🔍 *Analyzing recent team messages for alignment, deadlines, and responsibilities...*",
        )
        ack_ts = ack_msg.get("ts")

        # Execute analysis pipeline in async background loop
        async def _process_analysis():
            try:
                # Fetch bot's own user ID to filter self out
                auth_test = client.auth_test()
                bot_user_id = auth_test.get("user_id")

                # Resolve channel name
                channel_name = None
                try:
                    c_info = client.conversations_info(channel=channel_id)
                    channel_name = c_info.get("channel", {}).get("name")
                except Exception:
                    pass

                # Harvest messages & execute multi-agent analysis
                project = await slack_service.get_or_create_project_for_channel(
                    channel_id=channel_id, channel_name=channel_name
                )

                extracted_msgs = await slack_service.extract_channel_context(
                    client=client,
                    channel_id=channel_id,
                    thread_ts=thread_ts if event.get("thread_ts") else None,
                    limit=20,
                    bot_user_id=bot_user_id,
                )

                if not extracted_msgs:
                    client.chat_postMessage(
                        channel=channel_id,
                        thread_ts=thread_ts,
                        text=(
                            "⚠️ *No recent teammate statements found to analyze.*\n\n"
                            "Please have teammates share their goals, priorities, deadlines, or responsibilities "
                            "in the channel or thread before mentioning `@Mediator`."
                        ),
                    )
                    return

                await slack_service.ingest_messages_into_project(
                    project_id=project.id, messages=extracted_msgs, source="slack"
                )

                result = await analysis_service.trigger_analysis(project.id)
                formatted = slack_service.format_slack_analysis(result, project_id=project.id)

                # Post complete report in thread
                client.chat_postMessage(
                    channel=channel_id,
                    thread_ts=thread_ts,
                    blocks=formatted["blocks"],
                    text=formatted["text"],
                )

            except Exception as err:
                logger.error(f"Error processing Slack alignment analysis: {err}", exc_info=True)
                client.chat_postMessage(
                    channel=channel_id,
                    thread_ts=thread_ts,
                    text=f"❌ *Analysis failed*: `{str(err)}`. Please ensure team statements contain measurable goals or deadlines.",
                )

        # Run async coroutine safely
        try:
            loop = asyncio.get_event_loop()
            if loop.is_running():
                asyncio.create_task(_process_analysis())
            else:
                loop.run_until_complete(_process_analysis())
        except RuntimeError:
            new_loop = asyncio.new_event_loop()
            asyncio.set_event_loop(new_loop)
            new_loop.run_until_complete(_process_analysis())

    @app.action("open_dashboard_button")
    def handle_open_dashboard_action(ack, body):
        """Acknowledges clicks on the Open Dashboard button to prevent unhandled action warnings."""
        ack()

    return app


def start_slack_socket_mode(app: Optional[App] = None) -> Optional[SocketModeHandler]:
    """Starts the Slack Bolt Socket Mode Handler for development/local execution."""
    if not settings.is_slack_configured:
        logger.info("Slack tokens (SLACK_BOT_TOKEN / SLACK_APP_TOKEN) not provided. Socket Mode disabled.")
        return None

    app_instance = app or create_slack_app()
    if not app_instance:
        return None

    logger.info("Connecting to Slack via Socket Mode...")
    handler = SocketModeHandler(app_instance, settings.slack_app_token)
    return handler
