@pytest.mark.asyncio
async def test_frontend_backend_end_to_end_lifecycle(async_client):
    """Verify complete lifecycle that the React UI executes:
    1. Create project
    2. Add members
    3. Submit check-in responses with formatted 5-step text
    4. Run multi-agent analysis
    5. Retrieve synthesis report
    6. Record decision approval
    7. Retrieve team memory decisions
    """
    # 1. Create project
    proj_res = await async_client.post(
        "/api/projects",
        json={"title": "TeamAlign Q4 Milestone", "description": "Launch collaboration app."},
    )
    assert proj_res.status_code == 201
    project = proj_res.json()
    project_id = project["id"]
    assert project["title"] == "TeamAlign Q4 Milestone"

    # 2. Add members
    alex_res = await async_client.post(
        f"/api/projects/{project_id}/members",
        json={"name": "Alex Morgan", "role": "Frontend", "email": "alex@team.co"},
    )
    assert alex_res.status_code == 201

    sam_res = await async_client.post(
        f"/api/projects/{project_id}/members",
        json={"name": "Sam Rivera", "role": "Backend", "email": "sam@team.co"},
    )
    assert sam_res.status_code == 201

    taylor_res = await async_client.post(
        f"/api/projects/{project_id}/members",
        json={"name": "Taylor Kim", "role": "QA Lead", "email": "taylor@team.co"},
    )
    assert taylor_res.status_code == 201

    # 3. Submit check-ins using the 5-step format generated by the React CheckIn component
    alex_checkin = (
        "Goals: Complete responsive frontend experience.\n\n"
        "Priorities: Ensure UI polish and responsive layout.\n\n"
        "Timing: The project deadline is Saturday and I believe Taylor owns deployment.\n\n"
        "Ownership: I own frontend; Taylor owns deployment.\n\n"
        "Concerns: Rushing release without visual polish."
    )
    r1 = await async_client.post(
        f"/api/projects/{project_id}/responses",
        json={"member_name": "Alex Morgan", "raw_text": alex_checkin, "source": "checkin_survey"},
    )
    assert r1.status_code == 201

    sam_checkin = (
        "Goals: Deliver complete backend APIs.\n\n"
        "Priorities: Ensure database integrity.\n\n"
        "Timing: The project deadline is Sunday and we need full feature completion before launch.\n\n"
        "Ownership: I own backend routes and database storage.\n\n"
        "Concerns: Launching before backend services are stable."
    )
    r2 = await async_client.post(
        f"/api/projects/{project_id}/responses",
        json={"member_name": "Sam Rivera", "raw_text": sam_checkin, "source": "checkin_survey"},
    )
    assert r2.status_code == 201

    taylor_checkin = (
        "Goals: Ensure end-to-end quality and zero defects.\n\n"
        "Priorities: Dedicated test window before release.\n\n"
        "Timing: I believe Alex owns deployment, and we must complete thorough testing before launching anything.\n\n"
        "Ownership: I own regression testing; Alex owns deployment.\n\n"
        "Concerns: Launching without a mandatory 24-hour test window."
    )
    r3 = await async_client.post(
        f"/api/projects/{project_id}/responses",
        json={"member_name": "Taylor Kim", "raw_text": taylor_checkin, "source": "checkin_survey"},
    )
    assert r3.status_code == 201

    # Verify responses listed
    resp_list = await async_client.get(f"/api/projects/{project_id}/responses")
    assert resp_list.status_code == 200
    assert len(resp_list.json()) == 3

    # 4. Trigger multi-agent analysis
    analysis_res = await async_client.post(f"/api/projects/{project_id}/analyze")
    assert analysis_res.status_code == 200
    result = analysis_res.json()
    assert "perspectives_output" in result
    assert len(result["perspectives_output"]["perspectives"]) == 3
    assert "synthesis_output" in result
    assert "conflicts_output" in result
    conflicts = result["conflicts_output"]["conflicts"]
    assert len(conflicts) >= 2  # Saturday vs Sunday deadline contradiction + Alex/Taylor deployment ownership gap

    # 5. Retrieve alignment report
    align_res = await async_client.get(f"/api/projects/{project_id}/alignment")
    assert align_res.status_code == 200
    report = align_res.json()
    assert report["alignment_score"] > 0
    assert len(report["proposed_resolutions"]) >= 2
    first_res_id = report["proposed_resolutions"][0]["resolution_id"]

    # 6. Record human decision (Approve resolution)
    decision_payload = {
        "resolution_id": first_res_id,
        "action": "APPROVE",
        "decided_by": "Alex Morgan",
        "decision_text": report["proposed_resolutions"][0]["recommended_solution"],
    }
    dec_res = await async_client.post(f"/api/projects/{project_id}/decisions", json=decision_payload)
    assert dec_res.status_code == 201
    decision = dec_res.json()
    assert decision["status"] == "APPROVED"
    assert decision["decided_by"] == "Alex Morgan"

    # 7. Retrieve team memory decisions
    mem_res = await async_client.get(f"/api/projects/{project_id}/decisions")
    assert mem_res.status_code == 200
    mem_list = mem_res.json()
    assert len(mem_list) == 1
    assert mem_list[0]["resolution_id"] == first_res_id
