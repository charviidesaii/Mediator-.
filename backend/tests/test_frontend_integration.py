@pytest.mark.asyncio
async def test_dashboard_serves_react_frontend(async_client):
    """Verify that GET /dashboard serves the built React frontend HTML."""
    res = await async_client.get("/dashboard")
    assert res.status_code == 200
    assert "text/html" in res.headers.get("content-type", "")
    assert "<div id=\"root\"></div>" in res.text or "TeamAlign" in res.text


@pytest.mark.asyncio
async def test_root_browser_content_negotiation(async_client):
    """Verify that GET / with text/html Accept header serves the React dashboard."""
    res = await async_client.get("/", headers={"Accept": "text/html,application/xhtml+xml"})
    assert res.status_code == 200
    assert "text/html" in res.headers.get("content-type", "")


@pytest.mark.asyncio
async def test_root_json_client_negotiation(async_client):
    """Verify that GET / with application/json Accept header returns API metadata."""
    res = await async_client.get("/", headers={"Accept": "application/json"})
    assert res.status_code == 200
    data = res.json()
    assert "name" in data
    assert "dashboard_url" in data
    assert data["dashboard_url"] == "/dashboard"


